CREATE TABLE IF NOT EXISTS ARTICLE_VIEWER (
    ARTICLE_UID VARCHAR(40) NOT NULL COMMENT 'Article shared with the viewer',
    USER_UID VARCHAR(40) NOT NULL COMMENT 'User allowed to view the private article',
    REGISTRATION_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'Date the viewer was granted access',
    PRIMARY KEY (ARTICLE_UID, USER_UID),
    KEY IDX_ARTICLE_VIEWER_USER_UID (USER_UID),
    CONSTRAINT FK_ARTICLE_VIEWER_ARTICLE FOREIGN KEY (ARTICLE_UID) REFERENCES ARTICLE (ARTICLE_UID) ON DELETE CASCADE,
    CONSTRAINT FK_ARTICLE_VIEWER_USER FOREIGN KEY (USER_UID) REFERENCES `USER` (USER_UID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci
COMMENT='Users permitted to view a private article';
